import {
  TrainingMovement,
  TrainingPattern,
  TrainingMuscle,
  TrainingEquipment,
} from './training-planner.model';
import { MuscleGroup } from '../../core/models/workout.model';

function move(
  id: string,
  name: string,
  pattern: TrainingPattern,
  primary: TrainingMuscle,
  secondary: TrainingMuscle[],
  muscleGroup: MuscleGroup,
  equipment: TrainingEquipment[],
  compound: boolean,
  cue: string,
  unilateral = false,
): TrainingMovement {
  return {
    id,
    name,
    pattern,
    primary,
    secondary,
    muscleGroup,
    equipment,
    compound,
    cue,
    ...(unilateral ? { unilateral: true } : {}),
  };
}
